"""academic_activities backend — one shared document per portal project.

Generated by scripts/new-rack-service.mjs from src-lilak/def.js. The keys are
the declaration's (the items, each class with fields of its own, settings);
re-run with --sync after changing them there rather than editing this.

The document is stored whole and versioned; a save edited from an older version
is refused with 409. Every save keeps what it replaces (keep_days).
"""
import os
from pathlib import Path

from fastapi import FastAPI

from lilak_portal_auth.store import Document, mount_folders, mount_spa

DATA = Path(os.environ.get("ACADEMIC_ACTIVITIES_DATA_DIR", "./data"))
PROJECT = os.environ.get("PORTAL_PROJECT", "")
DIST = Path(os.environ.get("ACADEMIC_ACTIVITIES_DIST_DIR", "./dist"))

DOC = Document(DATA / "data.json", keys=("activities", "places", "proposals", "settings",), keep_days=30,
               links=(("activities", "place", "places"), ("activities", "proposal", "proposals")))

app = FastAPI(title="academic_activities")
DOC.mount(app, project=PROJECT)
mount_folders(app, DOC)   # a folder per record, under settings.folderRoots

# Must stay last: the catch-all would shadow /api/*.
mount_spa(app, DIST, name="academic_activities")
