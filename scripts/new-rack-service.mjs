#!/usr/bin/env node
/**
 * new-rack-service — a rack-list service from a declaration.
 *
 * A rack-list service is the kit's <RackService> fed one `def.js`; everything
 * else around it — the build, the 33-line backend on lilak_portal_auth.store,
 * the portal manifest, the first project — is the same every time. This writes
 * that, and leaves you the declaration.
 *
 *   node scripts/new-rack-service.mjs academic_activities \
 *        --title "학술 활동" --noun 활동 --unit 건 --color "#b45309" --icon calendar \
 *        [--project activities] [--out ~/web_service] [--force]
 *
 *   # after editing <name>/src-lilak/def.js:
 *   node scripts/new-rack-service.mjs academic_activities --sync
 *
 * --sync rewrites only backend/main.py, whose document keys come FROM the
 * declaration (the item list, every class with fields of its own, settings) —
 * so a class added in def.js is a key the backend owns without a second edit.
 *
 * Register the service with the portal afterwards (Services UI, or
 * /api/handshake) — a manifest alone is not a DB row.
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { resolve, join } from 'node:path'
import { homedir } from 'node:os'
import { pathToFileURL } from 'node:url'

const argv = process.argv.slice(2)
const args = { _: [] }
for (let i = 0; i < argv.length; i++) {
  const t = argv[i]
  if (t.startsWith('--')) {
    const n = argv[i + 1]
    if (n === undefined || n.startsWith('--')) args[t.slice(2)] = true
    else { args[t.slice(2)] = n; i++ }
  } else args._.push(t)
}
const expand = (p) => (p && p.startsWith('~') ? join(homedir(), p.slice(1)) : p)
const NAME = args.name || args._[0]
if (!NAME || !/^[a-z][a-z0-9_]*$/.test(NAME)) {
  console.error('error: a lowercase service name is required (e.g. academic_activities)')
  process.exit(1)
}
const ROOT = resolve(expand(args.out) || join(homedir(), 'web_service'))
const DIR = join(ROOT, NAME)
const DATA = resolve(expand(args.data) || join(ROOT, 'data'))
const ENV = NAME.toUpperCase()
const put = (rel, text, keep = false) => {
  const p = join(DIR, rel)
  if (keep && existsSync(p)) return
  if (existsSync(p) && !args.force && !keep && !args.sync) {
    console.error(`exists: ${p} (use --force)`); process.exit(1)
  }
  mkdirSync(join(p, '..'), { recursive: true })
  writeFileSync(p, text)
  console.log(`  wrote ${rel}`)
}

// ── the backend's keys, from the declaration ─────────────────────────────────
// The same rule as the kit's defineRack(): the items, every class that has
// fields of its own (a class worn through a field has no list), and settings.
// Kept here rather than imported because the kit is JSX and this is plain node.
async function keysOf() {
  const f = join(DIR, 'src-lilak', 'def.js')
  const def = (await import(`${pathToFileURL(f).href}?t=${Date.now()}`)).default
  return [def.item.key, ...(def.classes || []).filter((c) => !c.field).map((c) => c.k), 'settings']
}
async function writeBackend() {
  const keys = await keysOf()
  const py = keys.map((k) => JSON.stringify(k)).join(', ')
  put('backend/main.py', `"""${NAME} backend — one shared document per portal project.

Generated by scripts/new-rack-service.mjs from src-lilak/def.js. The keys are
the declaration's (the items, each class with fields of its own, settings);
re-run with --sync after changing them there rather than editing this.

The document is stored whole and versioned; a save edited from an older version
is refused with 409. Every save keeps what it replaces (keep_days).
"""
import os
from pathlib import Path

from fastapi import FastAPI

from lilak_portal_auth.store import Document, mount_spa

DATA = Path(os.environ.get("${ENV}_DATA_DIR", "./data"))
PROJECT = os.environ.get("PORTAL_PROJECT", "")
DIST = Path(os.environ.get("${ENV}_DIST_DIR", "./dist"))

DOC = Document(DATA / "data.json", keys=(${py},), keep_days=30)

app = FastAPI(title="${NAME}")
DOC.mount(app, project=PROJECT)

# Must stay last: the catch-all would shadow /api/*.
mount_spa(app, DIST, name="${NAME}")
`)
  return keys
}

if (args.sync) {
  const keys = await writeBackend()
  console.log(`\n✓ backend keys: ${keys.join(', ')}`)
  process.exit(0)
}

// ── a new service ────────────────────────────────────────────────────────────
const TITLE = args.title || NAME
const NOUN = args.noun || '항목'
const UNIT = args.unit || '개'
const COLOR = (args.color || '#475569').toLowerCase()
const ICON = args.icon || 'list'
const PROJECT = args.project || 'main'
const KEY = NAME.split('_').map((w) => w[0]).join('') || NAME.slice(0, 2)

console.log(`\nnew rack service: ${DIR}`)
put('package.json', JSON.stringify({
  name: `${NAME.replace(/_/g, '-')}-lilak`, version: '0.1.0', private: true, type: 'module',
  scripts: { build: 'vite build', 'lilak:dev': 'vite --host 127.0.0.1' },
  dependencies: {
    '@phosphor-icons/react': '^2.1.10', '@vitejs/plugin-react': '^4.3.1',
    react: '^19.2.7', 'react-dom': '^19.2.7', vite: '^5.3.1',
  },
}, null, 2) + '\n')
put('vite.config.js', `import { resolve } from 'path'
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

export default defineConfig({
  // Relative asset URLs: served behind the portal proxy under /pp/${NAME}/<project>/.
  base: './',
  plugins: [react()],
  resolve: {
    // One React for the app and the source-aliased kit.
    dedupe: ['react', 'react-dom'],
    alias: { 'lilak-ui': resolve(process.env.LILAK_UI_PATH || resolve(__dirname, '../lilak_ui'), 'src') },
  },
  server: { fs: { allow: [resolve(__dirname), resolve(__dirname, '../lilak_ui')] } },
})
`)
put('index.html', `<!doctype html>
<html lang="ko">
  <head>
    <base href="/" />
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>${TITLE}</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500;600&family=IBM+Plex+Sans:wght@400;500;600;700&family=IBM+Plex+Sans+KR:wght@400;500;600;700&display=swap" rel="stylesheet" />
  </head>
  <!-- rl-page: the page is the screen's height, so the table and the editor
       scroll on their own instead of the whole page growing. -->
  <body class="rl-page">
    <div id="root"></div>
    <script type="module" src="/src-lilak/main.jsx"></script>
  </body>
</html>
`)
put('src-lilak/main.jsx', `import { createRoot } from 'react-dom/client'
import { RackService } from 'lilak-ui/racklist'
import 'lilak-ui/racklist/rack.css'
import def from './def.js'

// The whole service is its declaration. Anything it cannot say goes in
// <RackService slots={…}> or registerType() — see lilak_ui/src/racklist/service.jsx.
createRoot(document.getElementById('root')).render(<RackService def={def} />)
`)
put('src-lilak/def.js', `/**
 * ${TITLE} — the declaration. Fields, classes and the listing rule; the screen
 * is derived from it. See lilak_ui/src/racklist/schema.js for every option.
 */
export default {
  name: '${NAME}', title: '${TITLE}', unit: '${UNIT}', key: '${KEY}',
  item: {
    key: 'items', noun: '${NOUN}', label: 'name',
    fields: [
      { k: 'name', label: '이름', type: 'text', col: 240, required: true },
      { k: 'date', label: '날짜', type: 'date', col: 96 },
      { k: 'tags', label: '태그', type: 'tags', col: 160 },
      { k: 'note', label: '메모', type: 'longtext' },
    ],
  },
  classes: [
    { k: 'tags', label: '태그', field: 'tags' },
  ],
  listing: { presets: [['기본', '{date} {name}', '⏎']] },
}
`, true)
put('portal-serve.sh', `#!/usr/bin/env sh
# Portal entry: build the app (non-fatal), then run the backend on the shared venv.
set -u
ROOT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
PORT="\${1:-8050}"
PATH="$PATH:/opt/homebrew/bin:/usr/local/bin"
export PATH
if command -v npm >/dev/null 2>&1; then
  LILAK_UI_PATH="\${LILAK_UI_PATH:-$ROOT_DIR/../lilak_ui}" npm --prefix "$ROOT_DIR" run build \\
    || echo "[portal-serve] build failed; serving existing dist/" >&2
fi
cd "$ROOT_DIR/backend"
${ENV}_DATA_DIR="\${PORTAL_PROJECT_DATA:-$ROOT_DIR/data}" ${ENV}_DIST_DIR="$ROOT_DIR/dist" \\
  exec "$ROOT_DIR/../service_manager/.venv/bin/python" -m uvicorn main:app --host 0.0.0.0 --port "$PORT"
`)
await writeBackend()

// ── the portal's side: the manifest and a first project ─────────────────────
const manifestDir = join(DATA, NAME)
mkdirSync(join(manifestDir, 'projects', PROJECT), { recursive: true })
const mf = join(manifestDir, 'service.json')
if (!existsSync(mf) || args.force) {
  writeFileSync(mf, JSON.stringify({
    kind: 'rack', mode: 'managed', label: TITLE,
    start: { cmd: `sh ${join(DIR, 'portal-serve.sh')} {port}`, cwd: DIR, env: {} },
    health: '/', entry: '/', url: null, token: null,
    identity: { accepts_portal_token: true, link_by: 'email' },
    capabilities: { multi_project: true, import_export: true },
    icon: ICON, color: COLOR, open: 'panel',
  }, null, 2) + '\n')
  console.log(`  wrote ${mf}`)
}

if (!args['no-install']) {
  console.log('\n  npm install …')
  const r = spawnSync('npm', ['install', '--silent'], { cwd: DIR, stdio: 'inherit' })
  if (r.status !== 0) console.error('  npm install failed — run it in the service directory')
}

console.log(`
✓ ${NAME}
  edit:      ${join(DIR, 'src-lilak', 'def.js')}
  then:      node scripts/new-rack-service.mjs ${NAME} --sync   (backend keys from def.js)
  manifest:  ${mf}   (project: ${PROJECT})
  register:  Services UI, or /api/handshake — a manifest alone is not a DB row
`)
