"""project_manager backend — one shared document per portal project.

Generated by scripts/new-rack-service.mjs, keys set by hand: the declaration
imports the kit's dictionary, which --sync (plain node) cannot load. Keep them
the declaration's — the items (projects), each class with fields of its own
(none), settings — plus `inbox`, which only the routes below touch.

The document is stored whole and versioned; a save edited from an older version
is refused with 409. Every save keeps what it replaces (keep_days).

Inbox — candidates something automatic (the Claude mail task) proposes, waiting
for a manager's yes before they become a note or an activity. The task drops
one file per candidate into `<project data>/inbox-drop/`:
    {id, createdAt, target: "note"|"activity", fields: {...},
     source: {from, subject, date}, remark}
and every minute (and at start) they are taken in as records of the `inbox`
class — flat, so the kit's table and editor read them as any class's: the
fields beside `target`, `status` (waiting | approved | discarded), `from`,
`date`, `subject`, `remark` (the file goes to `inbox-drop/imported/`). The page
approves one by making it in the service it belongs to and saving the record
with `status`, `decidedAt` and `made` ({svc, proj, id}). A discard is dropped
after DISCARD_KEEP_DAYS. The list is kept waiting first, then oldest first.
"""
import copy
import json
import os
import re
import shutil
import threading
import time
from datetime import datetime, timedelta
from pathlib import Path

from fastapi import FastAPI

from lilak_portal_auth.store import Document, mount_folders, mount_spa

DATA = Path(os.environ.get("PROJECT_MANAGER_DATA_DIR", "./data"))
PROJECT = os.environ.get("PORTAL_PROJECT", "")
DIST = Path(os.environ.get("PROJECT_MANAGER_DIST_DIR", "./dist"))
DROP = DATA / "inbox-drop"
DISCARD_KEEP_DAYS = 10

DOC = Document(DATA / "data.json", keys=("projects", "inbox", "settings",), keep_days=30)

app = FastAPI(title="project_manager")
DOC.mount(app, project=PROJECT)
mount_folders(app, DOC)   # a folder per project, under settings.folderRoots


def _flat(c: dict) -> dict:
    """A candidate as the file has it → a record of the `inbox` class: its
    fields beside its target (a note's tags as `noteTags`), its mail's
    sender, date and subject as `from`, `date`, `subject`."""
    if "fields" not in c and "source" not in c:
        return c
    out = {k: v for k, v in c.items() if k not in ("fields", "source")}
    for k, v in (c.get("fields") or {}).items():
        out["noteTags" if k == "tags" else k] = " ".join(v) if isinstance(v, list) else v
    src = c.get("source") or {}
    out.update({k: src.get(k) or "" for k in ("from", "date", "subject")})
    out.setdefault("status", "waiting")
    return out


_RANK = {"waiting": 0, "approved": 1, "checked": 1, "discarded": 2}


def _order(inbox: list) -> list:
    return sorted(inbox, key=lambda c: (_RANK.get(c.get("status"), 0), str(c.get("createdAt") or ""), str(c.get("id"))))


def tick() -> bool:
    """Take in what was dropped, flatten what came in before, drop old
    discards, keep the order. True when the document changed."""
    cutoff = (datetime.now().astimezone() - timedelta(days=DISCARD_KEEP_DAYS)).isoformat(timespec="seconds")
    files = sorted(DROP.glob("*.json")) if DROP.is_dir() else []
    with DOC.lock:
        cur = DOC.read()
        inbox = [_flat(c) for c in copy.deepcopy(cur.get("inbox") or [])]   # never edit cur in place
        have = {str(c.get("id")) for c in inbox}
        for f in files:
            try:
                c = json.loads(f.read_text(encoding="utf-8"))
            except Exception:
                continue                   # half-written: the next tick takes it
            if isinstance(c, dict) and re.fullmatch(r"[A-Za-z0-9_-]{1,80}", str(c.get("id") or "")) \
                    and c.get("target") in ("note", "activity") and str(c["id"]) not in have:
                inbox.append(_flat(c))
                have.add(str(c["id"]))
            (DROP / "imported").mkdir(parents=True, exist_ok=True)
            shutil.move(str(f), str(DROP / "imported" / f.name))
        inbox = _order([c for c in inbox if not (c.get("status") == "discarded" and str(c.get("decidedAt") or "") < cutoff)])
        if inbox == (cur.get("inbox") or []):
            return False
        DOC.write({**cur, "inbox": inbox}, "inbox", replaces=cur)
        return True


def _ticker() -> None:
    while True:
        try:
            tick()
        except Exception as e:             # noqa: BLE001 — a bad file must not stop the inbox
            print(f"[inbox] tick failed: {e}", flush=True)
        time.sleep(60)


if os.environ.get("PM_INBOX_TIMER", "1") != "0":
    threading.Thread(target=_ticker, daemon=True, name="inbox").start()


# Must stay last: the catch-all would shadow /api/*.
mount_spa(app, DIST, name="project_manager")
